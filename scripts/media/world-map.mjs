/**
 * Builds the dotted world map used by the Global Presence section.
 * Output: public/media/world-dots.svg (static, cacheable) and src/content/world-map.ts (city coordinates).
 */
import fs from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";
import land110 from "world-atlas/land-110m.json" with { type: "json" };

// Equirectangular crop: 168°W → 192°E, 80°N → 56°S (keeps Alaska + Chukotka together, drops Antarctica).
const LON0 = -168;
const LAT_TOP = 80;
const LAT_BOTTOM = -56;
const W = 1000;
const H = Math.round((W * (LAT_TOP - LAT_BOTTOM)) / 360);
const STEP = 8;
const R = 1.6;
const land = feature(land110, land110.objects.land);
const projection = Object.assign(
  ([lon, lat]) => [(((lon - LON0 + 360) % 360) / 360) * W, ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H],
  { invert: ([x, y]) => [((LON0 + (x / W) * 360 + 540) % 360) - 180, LAT_TOP - (y / H) * (LAT_TOP - LAT_BOTTOM)] },
);

let d = "";
let count = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const p = projection.invert([x, y]);
    if (geoContains(land, p)) {
      d += `M${(x - R).toFixed(1)} ${y.toFixed(1)}a${R} ${R} 0 1 0 ${2 * R} 0a${R} ${R} 0 1 0 ${-2 * R} 0`;
      count++;
    }
  }
}
fs.writeFileSync(
  "public/media/world-dots.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path fill="#3b352f" d="${d}"/></svg>`,
);

